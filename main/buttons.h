/* Button bits, the same layout as Keen's KEEN_BTN_* and Adventure's UI_BTN_*. */
#pragma once
enum {
    BTN_UP    = 1 << 0,
    BTN_DOWN  = 1 << 1,
    BTN_LEFT  = 1 << 2,
    BTN_RIGHT = 1 << 3,
    BTN_A     = 1 << 4,
    BTN_B     = 1 << 5,
    BTN_C     = 1 << 6,
    BTN_D     = 1 << 7,
    BTN_OK    = 1 << 8,
};
